"""The macOS Seatbelt profile for the contained server (``sandbox-exec -f <profile>``).

Seatbelt applies the last rule that matches, so the profile allows by default, then denies
reads under the home directory, ``/Users`` (other users, ``/Users/Shared``) and ``/Volumes``
(other disks and data volumes), every write, and all network, and then allows back exactly
what :class:`~entrabot.sandbox.policy.ContainmentPolicy` lists:

- reads there only of the repository, the virtual environment, Entrabot's state and
  ``~/Library/Keychains`` (the Security framework reads the login keychain file in the client
  process: without it the certificate key cannot be found and the sign-in stops, measured on
  macOS 27). The folders above those can be looked at (``stat``, so paths resolve) but not
  listed. The system (``/System``, ``/usr``, ``/Library``, ``/opt``, ``/private``) stays
  readable: Python and its libraries load from there;
- writes only to Entrabot's state, its sign-in cache and ``/dev/null``;
- outbound connections only to the launcher's proxy on loopback. Seatbelt cannot filter by
  host name, so host filtering is the proxy's job; DNS is not reachable either.

Everything the server starts (a persona-sati token command, for one) inherits the profile.
What it cannot do is have something else start a program for it: opening a file or an app
through Launch Services (``open``) and sending Apple Events to other apps are denied, because
a program started that way runs outside the sandbox.
"""

from __future__ import annotations

import os
from pathlib import Path

from entrabot.sandbox.policy import ContainmentPolicy


def _real(path: Path) -> str:
    # Seatbelt matches resolved paths: /var is /private/var, /tmp is /private/tmp.
    return os.path.realpath(str(path))


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _subpaths(paths: list[Path]) -> str:
    return " ".join(f"(subpath {_quote(_real(path))})" for path in paths)


HIDDEN_ROOTS: tuple[Path, ...] = (Path("/Users"), Path("/Volumes"))


def _parents(paths: list[Path]) -> list[str]:
    found: list[str] = []
    for path in paths:
        for parent in Path(_real(path)).parents:
            if str(parent) not in found:
                found.append(str(parent))
    return found


def profile(
    policy: ContainmentPolicy,
    *,
    proxy_port: int,
    hidden_roots: tuple[Path, ...] | None = None,
) -> str:
    home = _real(policy.home)
    keychains = Path(home) / "Library" / "Keychains"
    readable = [*policy.read_only, *policy.read_write, keychains]
    writable = [*policy.read_write]
    roots = hidden_roots if hidden_roots is not None else (policy.home, *HIDDEN_ROOTS)
    hidden = list(dict.fromkeys(_real(root) for root in roots))
    lookable = " ".join(
        f"(literal {_quote(path)})" for path in dict.fromkeys([*hidden, *_parents(readable)])
    )
    lines = [
        "(version 1)",
        ";; Generated by entrabot.sandbox.seatbelt. Later rules win.",
        "(allow default)",
        "",
        ";; Files: nothing under the home directory, /Users or /Volumes but what is listed.",
        *(f"(deny file-read* (subpath {_quote(path)}))" for path in hidden),
        f"(allow file-read-metadata {lookable})",
        f"(allow file-read* {_subpaths(readable)})",
        "",
        ";; Writes: Entrabot's own state only.",
        "(deny file-write*)",
        f'(allow file-write* {_subpaths(writable)} (literal "/dev/null"))',
        "",
        ";; Network: the launcher's allowlisting proxy only.",
        "(deny network*)",
        f'(allow network-outbound (remote ip "localhost:{int(proxy_port)}"))',
        ";; Listening on loopback only: the delegated sign-in's browser redirect (MSAL).",
        '(allow network-bind network-inbound (local ip "localhost:*"))',
        "",
        ";; No asking the system to start a program (Launch Services: an app it starts runs",
        ";; outside this sandbox), and no scripting other apps with Apple Events.",
        "(deny lsopen)",
        "(deny appleevent-send)",
        "",
    ]
    return "\n".join(lines)


def command(profile_path: Path, argv: list[str]) -> list[str]:
    return ["/usr/bin/sandbox-exec", "-f", str(profile_path), *argv]
